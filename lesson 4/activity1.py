# Storing Values
tree1 = 98
tree2 = 94
tree3 = 41
tree4 = 95
tree5 = 11

# Finding the total of trees
# Changed 'sum' to 'total_sum' to avoid overwriting Python's built-in sum function
total_sum = tree1 + tree2 + tree3 + tree4 + tree5
print("the sum of all the 5 trees is: ", total_sum)

# Finding the average of trees
average = total_sum / 5
print("the average of all the trees is :", average)
